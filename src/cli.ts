interface ExecutionOptions {
	workingDir: string;
	tfPath: string;
	args: string[];
	all: boolean;
}

interface FormatOptions {
	workingDir: string;
	tfPath: string;
	check: boolean;
	diff: boolean;
	stdin: boolean;
	files: string[];
}

function parseExecutionArgs(argv: string[]): ExecutionOptions & {command: string} {
	let workingDir = process.cwd();
	let tfPath = process.env.TG_TF_PATH ?? process.env.TERRAGRUNT_TFPATH ?? 'tofu';
	let all = false;
	let index = 0;
	while (index < argv.length) {
		const argument = argv[index];
		if (argument === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			index++;
			continue;
		}
		if (argument.startsWith('--working-dir=')) {
			const value = argument.slice('--working-dir='.length);
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			index++;
			continue;
		}
		if (argument === '--tf-path') {
			const value = argv[++index];
			if (!value) throw new Error('--tf-path requires a path');
			tfPath = value;
			index++;
			continue;
		}
		if (argument.startsWith('--tf-path=')) {
			tfPath = argument.slice('--tf-path='.length);
			if (!tfPath) throw new Error('--tf-path requires a path');
			index++;
			continue;
		}
		if (isPassthroughFlag(argument)) {
			index++;
			continue;
		}
		if (argument === '--all' || argument === '-a') { all = true; index++; continue; }
		if (argument === '--') {
			index++;
			break;
		}
		break;
	}
	const command = argv[index];
	if (!command || command.startsWith('-')) throw new Error('A Terraform/OpenTofu command is required');
	// Flags belonging to this tool are dropped wherever they appear, not only
	// before the command. Scripts write `run-all apply
	// --terragrunt-non-interactive`, so the flag lands AFTER the command, and
	// forwarding it to OpenTofu makes it reject the whole invocation.
	// Flags that take a VALUE have to consume that value too, or the path is
	// forwarded to OpenTofu as a positional argument. Terragrunt accepts its
	// own flags on either side of the command and consumes them; forwarding
	// them produced "Failed to parse command-line flags" from tofu on an
	// invocation terragrunt accepts.
	const tail = argv.slice(index + 1);
	const args: string[] = [];
	for (let position = 0; position < tail.length; position++) {
		const argument = tail[position];
		if (argument === '--all' || argument === '-a') continue;
		if (isPassthroughFlag(argument)) continue;
		const valued = valuedExecutionFlag(argument);
		if (valued) {
			// `--flag value` consumes the next argument; `--flag=value` is one.
			if (!argument.includes('=')) position++;
			if (valued === 'working-dir') {
				const value = argument.includes('=') ? argument.split('=').slice(1).join('=') : tail[position];
				if (!value) throw new Error('--working-dir requires a path');
				workingDir = path.resolve(value);
			} else if (valued === 'tf-path') {
				const value = argument.includes('=') ? argument.split('=').slice(1).join('=') : tail[position];
				if (!value) throw new Error('--tf-path requires a path');
				tfPath = value;
			}
			continue;
		}
		args.push(argument);
	}
	return {workingDir, tfPath, command, args, all};
}

/**
 * Whether an argument is one of this tool's flags that carries a value.
 *
 * Named rather than pattern-matched, because the answer decides whether the
 * NEXT argument is a value to consume or a flag for OpenTofu, and guessing
 * either way corrupts the invocation. The `--terragrunt-` spellings are
 * accepted alongside the current ones, as everywhere else.
 */
function valuedExecutionFlag(argument: string): 'working-dir' | 'tf-path' | undefined {
	const bare = argument.split('=')[0];
	const name = bare.startsWith('--terragrunt-') ? `--${bare.slice('--terragrunt-'.length)}` : bare;
	if (name === '--working-dir') return 'working-dir';
	if (name === '--tf-path' || name === '--tfpath') return 'tf-path';
	return undefined;
}

function parseFormatArgs(argv: string[]): FormatOptions | 'help' {
	let workingDir = process.cwd();
	let tfPath = process.env.TG_TF_PATH ?? process.env.TERRAGRUNT_TFPATH ?? 'tofu';
	let check = false;
	let diff = false;
	let stdin = false;
	const files: string[] = [];
	for (let index = 0; index < argv.length; index++) {
		const argument = argv[index];
		if (argument === '--help' || argument === '-h') return 'help';
		if (argument === '--check') { check = true; continue; }
		if (argument === '--diff') { diff = true; continue; }
		if (argument === '--stdin') { stdin = true; continue; }
		if (argument === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			continue;
		}
		if (argument.startsWith('--working-dir=')) {
			const value = argument.slice('--working-dir='.length);
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			continue;
		}
		if (argument === '--tf-path') {
			const value = argv[++index];
			if (!value) throw new Error('--tf-path requires a path');
			tfPath = value;
			continue;
		}
		if (argument.startsWith('--tf-path=')) {
			tfPath = argument.slice('--tf-path='.length);
			if (!tfPath) throw new Error('--tf-path requires a path');
			continue;
		}
		if (isPassthroughFlag(argument)) continue;
		if (argument.startsWith('-')) throw new Error(`Unknown format option ${argument}`);
		files.push(path.resolve(workingDir, argument));
	}
	if (check && diff) throw new Error('--check and --diff cannot be used together');
	if (stdin && files.length > 0) throw new Error('--stdin cannot be combined with file paths');
	return {workingDir, tfPath, check, diff, stdin, files};
}

async function formatHCL(argv: string[]): Promise<number> {
	const options = parseFormatArgs(argv);
	if (options === 'help') {
		console.log('Usage: tghclp hcl format [--check|--diff|--stdin] [--tf-path <path>] [files...]');
		return 0;
	}
	const targets = options.stdin
		? []
		: options.files.length > 0
			? options.files
			: (await collectFiles(options.workingDir)).filter(file => !file.endsWith('.json'));
	if (!options.stdin && targets.length === 0) throw new Error(`No Terragrunt HCL files found under ${options.workingDir}`);
	const tempRoot = await fs.mkdtemp(path.join(options.workingDir, '.tghclp-format-'));
	const changed: string[] = [];
	try {
		if (options.stdin) {
			const original = fsSync.readFileSync(0, 'utf8');
			const tempFile = path.join(tempRoot, 'stdin.tf');
			await fs.writeFile(tempFile, original);
			const result = spawnSync(options.tfPath, ['fmt', tempFile], {encoding: 'utf8', shell: false});
			if (result.error || result.status !== 0) throw new Error(result.error?.message ?? (result.stderr || `Formatter exited with ${result.status}`));
			const formatted = await fs.readFile(tempFile, 'utf8');
			if (options.check && formatted !== original) return 1;
			if (options.diff) {
				if (formatted !== original) process.stdout.write(`--- stdin\n+++ stdin\n${formatted}`);
				return 0;
			}
			process.stdout.write(formatted);
			return 0;
		}
		for (const target of targets) {
			const root = await fs.realpath(options.workingDir);
			const realTarget = await fs.realpath(target);
			const relativeTarget = path.relative(root, realTarget);
			if (relativeTarget === '..' || relativeTarget.startsWith(`..${path.sep}`) || path.isAbsolute(relativeTarget)) {
				throw new Error(`Format target is outside the working directory: ${target}`);
			}
			const info = await fs.stat(target);
			if (!info.isFile()) throw new Error(`Format target is not a file: ${target}`);
			await fs.access(target);
			const original = await fs.readFile(target, 'utf8');
			const tempFile = path.join(tempRoot, `${changed.length}.tf`);
			await fs.writeFile(tempFile, original);
			const result = spawnSync(options.tfPath, ['fmt', tempFile], {encoding: 'utf8', shell: false});
			if (result.error || result.status !== 0) throw new Error(result.error?.message ?? (result.stderr || `Formatter exited with ${result.status}`));
			const formatted = await fs.readFile(tempFile, 'utf8');
			if (formatted === original) continue;
			changed.push(target);
			if (options.check) continue;
			if (options.diff) {
				process.stdout.write(`--- ${target}\n+++ ${target}\n${formatted}`);
				continue;
			}
			await fs.writeFile(target, formatted);
			process.stdout.write(`${target} was updated\n`);
		}
		if (options.check) {
			for (const target of changed) process.stdout.write(`${target} needs formatting\n`);
			return changed.length > 0 ? 1 : 0;
		}
		return 0;
	} finally {
		await fs.rm(tempRoot, {recursive: true, force: true});
	}
}

function offsetPosition(content: string, offset: number): {line: number; character: number} {
	const lines = content.slice(0, offset).split('\n');
	return {line: lines.length - 1, character: lines[lines.length - 1].length};
}

function hclValue(value: unknown): string {
	if (typeof value === 'string') return JSON.stringify(value);
	if (typeof value === 'boolean' || typeof value === 'number') return String(value);
	if (value === null) return 'null';
	if (Array.isArray(value)) return `[${value.map(hclValue).join(', ')}]`;
	if (typeof value === 'object') return `{ ${Object.entries(value as Record<string, unknown>).map(([key, item]) => `${key} = ${hclValue(item)}`).join(', ')} }`;
	throw new Error(`Cannot serialize stack value of type ${typeof value}`);
}

async function copyDirectory(source: string, target: string): Promise<void> {
	await fs.mkdir(target, {recursive: true});
	for (const entry of await fs.readdir(source, {withFileTypes: true})) {
		const from = path.join(source, entry.name);
		const to = path.join(target, entry.name);
		if (entry.isDirectory()) await copyDirectory(from, to);
		else if (entry.isFile()) await fs.copyFile(from, to);
		else throw new Error(`Unsupported stack source entry: ${from}`);
	}
}

export async function stackGenerate(argv: string[]): Promise<number> {
	let workingDir = process.cwd();
	for (let index = 0; index < argv.length; index++) {
		const argument = argv[index];
		if (argument === '--help' || argument === '-h') {
			console.log('Usage: tghclp stack generate [--working-dir <path>]');
			return 0;
		}
		if (argument === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			continue;
		}
		if (argument.startsWith('--working-dir=')) {
			workingDir = path.resolve(argument.slice('--working-dir='.length));
			continue;
		}
		if (isPassthroughFlag(argument)) continue;
		if (argument.startsWith('-')) throw new Error(`Unknown stack generate option ${argument}`);
	}
	const stackPath = path.join(workingDir, 'terragrunt.stack.hcl');
	const content = await fs.readFile(stackPath, 'utf8');
	const document = new ParsedDocument(new Workspace(), pathToFileURL(stackPath).toString(), content);
	const ast: any = document.getAST();
	if (!ast || document.getDiagnostics().length > 0) throw new Error(`Invalid stack configuration: ${stackPath}`);
	const evaluator = evaluatorFor();
	const blocks: any[] = [];
	const visit = (node: any): void => {
		if (node.type === 'block' && (node.value === 'unit' || node.value === 'stack')) blocks.push(node);
		for (const child of node.children ?? []) visit(child);
	};
	visit(ast);
	if (blocks.length === 0) {
		console.warn(`No stack files found in ${workingDir} Nothing to generate.`);
		return 0;
	}
	for (const block of blocks) {
		const attribute = (name: string): any => block.children?.find((child: any) => child.type === 'attribute' && child.value === name);
		const evaluate = async (name: string): Promise<unknown> => {
			const item = attribute(name);
			if (!item) return undefined;
			const value = item.children?.find((child: any) => child.type !== 'attribute_identifier');
			if (!value?.location?.start || value.location.start.offset === undefined) throw new Error(`${name} in ${block.value} is missing a value`);
			const result = await evaluator.evaluateAtPosition(stackPath, content, workingDir, offsetPosition(content, value.location.start.offset));
			if (!result) throw new Error(`Unable to evaluate ${name} in ${stackPath}`);
			return runtimeValueToPlain(result);
		};
		const source = await evaluate('source');
		const generatedPath = await evaluate('path');
		if (typeof source !== 'string' || typeof generatedPath !== 'string' || source === '' || generatedPath === '') throw new Error(`${block.value} requires non-empty source and path attributes`);
		const root = await fs.realpath(workingDir);
		const acquired = await acquireModuleSource(source, root);
		const sourceRelative = path.relative(root, acquired.root);
		if (isLocalSource(splitModuleSource(source).repository) && (sourceRelative === '..' || sourceRelative.startsWith(`..${path.sep}`) || path.isAbsolute(sourceRelative))) {
			await acquired.cleanup();
			throw new Error(`Stack source must be inside the working directory: ${source}`);
		}
		const noDot = Boolean(await evaluate('no_dot_terragrunt_stack'));
		const targetDir = path.resolve(root, noDot ? generatedPath : path.join('.terragrunt-stack', generatedPath));
		try {
			const realSource = acquired.root;
			const relativeTarget = path.relative(root, targetDir);
			if (relativeTarget === '..' || relativeTarget.startsWith(`..${path.sep}`) || path.isAbsolute(relativeTarget)) throw new Error(`Generated stack target is outside the working directory: ${targetDir}`);
			if (realSource === targetDir) throw new Error(`Generated stack source and target are identical: ${targetDir}`);
			await fs.access(realSource);
			await fs.rm(targetDir, {recursive: true, force: true});
			await copyDirectory(realSource, targetDir);
			const values = await evaluate('values');
			if (values !== undefined) {
				if (values === null || typeof values !== 'object' || Array.isArray(values)) throw new Error(`${block.value} values must evaluate to an object`);
				const entries = Object.entries(values as Record<string, unknown>).sort(([left], [right]) => left.localeCompare(right));
				const width = Math.max(...entries.map(([key]) => key.length));
				const valuesText = '# Auto-generated by the terragrunt.stack.hcl file by Terragrunt. Do not edit manually\n' + entries.map(([key, value]) => `${key.padEnd(width)} = ${hclValue(value)}`).join('\n') + '\n';
				await fs.writeFile(path.join(targetDir, 'terragrunt.values.hcl'), valuesText);
			}
		} finally {
			await acquired.cleanup();
		}
		console.log(`Generated ${block.value} ${String(block.children?.find((child: any) => child.type === 'parameter')?.value ?? '')}`.trim());
	}
	return 0;
}

async function stackLifecycle(command: 'run' | 'output' | 'clean', argv: string[]): Promise<number> {
	let workingDir = process.cwd();
	for (let index = 0; index < argv.length; index++) {
		if (argv[index] === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
		} else if (argv[index]?.startsWith('--working-dir=')) {
			workingDir = path.resolve(argv[index].slice('--working-dir='.length));
		} else if (argv[index] === '--help' || argv[index] === '-h') {
			console.log(`Usage: tghclp stack ${command} [--working-dir <path>]${command === 'run' || command === 'output' ? ' <command> [arguments...]' : ''}`);
			return 0;
		}
	}
	const root = await fs.realpath(workingDir);
	const generated = path.join(root, '.terragrunt-stack');
	if (command === 'clean') {
		await fs.rm(generated, {recursive: true, force: true});
		return 0;
	}
	await stackGenerate(argv.filter((argument, index) => argument === '--working-dir' || argument.startsWith('--working-dir=') || (argv[index - 1] === '--working-dir')));
	const generatedRoot = await fs.realpath(generated);
	const executionArgs = ['--all', '--working-dir', generatedRoot];
	for (let index = 0; index < argv.length; index++) {
		if (argv[index] === '--working-dir') { index++; continue; }
		if (argv[index]?.startsWith('--working-dir=')) continue;
		if (isPassthroughFlag(argv[index])) { executionArgs.push(argv[index]); continue; }
		executionArgs.push(argv[index]);
	}
	if (executionArgs.length === 3) throw new Error(`stack ${command} requires a command`);
	return executeTerraformCommand(executionArgs);
}

async function renderConfig(argv: string[]): Promise<number> {
	let workingDir = process.cwd();
	let configName = 'terragrunt.hcl';
	let json = false;
	for (let index = 0; index < argv.length; index++) {
		const argument = argv[index];
		if (argument === '--help' || argument === '-h') {
			console.log('Usage: tghclp render --json [--working-dir <path>] [--config <file>]');
			return 0;
		}
		if (argument === '--json' || argument === '--format=json') { json = true; continue; }
		if (argument === '--format') {
			const format = argv[++index];
			if (format !== 'json') throw new Error('Only JSON render output is supported');
			json = true;
			continue;
		}
		if (argument === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			continue;
		}
		if (argument === '--config') {
			const value = argv[++index];
			if (!value) throw new Error('--config requires a path');
			configName = value;
			continue;
		}
		if (argument.startsWith('-')) throw new Error(`Unknown render option ${argument}`);
	}
	if (!json) throw new Error('Render output requires --json or --format=json');
	const configPath = path.resolve(workingDir, configName);
	const root = await fs.realpath(workingDir);
	const realConfig = await fs.realpath(configPath);
	const relative = path.relative(root, realConfig);
	if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) throw new Error(`Render configuration is outside the working directory: ${configPath}`);
	const content = await fs.readFile(realConfig, 'utf8');
	if (realConfig.endsWith('.json')) {
		const parsed: unknown = JSON.parse(content);
		validateJSONShape(parsed, path.basename(realConfig));
		process.stdout.write(`${JSON.stringify(parsed)}\n`);
		return 0;
	}
	const evaluator = evaluatorFor();
	const result = await evaluator.evaluateRenderedConfig(realConfig, content, root);
	process.stdout.write(`${JSON.stringify(runtimeValueToPlain(result))}\n`);
	return 0;
}

function generatedEntries(value: unknown): Array<[string, Record<string, unknown>]> {
	if (value === null || typeof value !== 'object' || Array.isArray(value)) return [];
	return Object.entries(value as Record<string, unknown>).map(([name, entry]) => {
		if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) throw new Error(`generate "${name}" must evaluate to an object`);
		return [name, entry as Record<string, unknown>];
	});
}

/**
 * The outputs of a unit this one declares a `dependency` on.
 *
 * `dependency.<name>.outputs.<x>` is how one unit reads another, and it is
 * the ordinary way a Terragrunt workspace is wired: the step that provisions
 * reads what the step that planned produced. Without this the reference threw
 * "Dependency has no evaluated outputs" and no configuration using one could
 * be run at all -- the hook existed and nothing supplied it.
 *
 * Resolved the way terragrunt resolves it: find the named block, evaluate its
 * `config_path`, and ask OpenTofu for that unit's outputs. A unit that has
 * not been applied has none, and saying so names the step to run rather than
 * failing on a missing attribute several levels deeper.
 */
/**
 * The OpenTofu or Terraform binary a dependency's outputs are read with.
 *
 * Validation has no `--tf-path` of its own -- it is not running anything --
 * so it follows the same environment variables terragrunt reads, and falls
 * back to the same default.
 */
/**
 * An evaluator configured the way every command needs one.
 *
 * The options were spelled out at eleven call sites. That is how
 * `resolveDependency` came to be supplied at two of them and missing at the
 * rest: a unit reading `dependency.<name>.outputs` evaluated in one command
 * and failed in another, for no reason a reader could see.
 */
function evaluatorFor(options: {
	terraformCommand?: string;
	terraformCliArgs?: string[];
	experiments?: string[];
	tfPath?: string;
} = {}): ConfigEvaluator {
	const tfPath = options.tfPath ?? tfPathForDependencies();
	return new ConfigEvaluator({
		environmentVariables: process.env as Record<string, string>,
		terraformCommand: options.terraformCommand ?? '',
		terraformCliArgs: options.terraformCliArgs ?? [],
		...(options.experiments ? {experiments: options.experiments} : {}),
		workspaceTrusted: true,
		allowedPaths,
		resolveDependency: (from, name) => dependencyOutputs(from, name, tfPath),
	});
}

function tfPathForDependencies(): string {
	return process.env.TG_TF_PATH ?? process.env.TERRAGRUNT_TFPATH ?? 'tofu';
}

async function dependencyOutputs(
	configPath: string,
	name: string,
	tfPath: string
): Promise<RuntimeValue<ValueType> | undefined> {
	const content = await fs.readFile(configPath, 'utf8');
	const ast: any = parse(content, {grammarSource: configPath, tracer: {trace() {}}});
	let target: string | undefined;
	const visit = async (node: any): Promise<void> => {
		if (target) return;
		if (node.type === 'block' && node.value === 'dependency') {
			const label = node.children?.find((child: any) => child.type === 'parameter');
			if (label && String(label.value) === name) {
				const attribute = node.children?.find(
					(child: any) => child.type === 'attribute' && child.value === 'config_path'
				);
				const valueNode = attribute?.children?.find((child: any) => child.type !== 'attribute_identifier');
				if (!valueNode) throw new Error(`dependency "${name}" in ${configPath} is missing config_path`);
				// Read as a literal, not evaluated. Evaluating an expression in
				// this file re-enters evaluation of the whole unit -- including
				// the `dependency.<name>.outputs` reference that called this --
				// and the recursion surfaces as the very error it is resolving.
				//
				// `config_path` is a path to a sibling unit. An interpolated one
				// is refused rather than guessed at, because a path this cannot
				// read is a dependency it would silently fail to find.
				const literal = String(valueNode.value ?? '');
				if (!literal) {
					throw new Error(
						`dependency "${name}" in ${configPath} has a config_path this cannot read ` +
						'without evaluating the unit it belongs to. Write it as a literal path.'
					);
				}
				target = path.resolve(path.dirname(configPath), literal);
			}
		}
		for (const child of node.children ?? []) await visit(child);
	};
	await visit(ast);
	if (!target) return undefined;

	const result = spawnSync(tfPath, ['output', '-json'], {cwd: target, encoding: 'utf8'});
	if (result.status !== 0) {
		throw new Error(
			`dependency "${name}" has no outputs to read from ${target}.\n` +
			`Apply that unit first. ${(result.stderr || '').trim().split('\n')[0]}`
		);
	}
	// `output -json` gives {name: {value, type, sensitive}}; a dependency reads
	// the values.
	const raw = JSON.parse(result.stdout || '{}') as Record<string, {value: unknown}>;
	const outputs = new Map<string, RuntimeValue<ValueType>>();
	for (const [key, entry] of Object.entries(raw)) {
		outputs.set(key, convertToRuntimeValue(entry.value));
	}
	return makeObjectValue(new Map([['outputs', makeObjectValue(outputs)]]));
}

async function materializeGeneratedFiles(
	configPath: string,
	content: string,
	workDir: string,
	tfPath: string
): Promise<void> {
	// A generate block may interpolate a dependency's outputs, so rendering one
	// needs the same resolution running a unit does.
	const evaluator = evaluatorFor({tfPath});
	const rendered = runtimeValueToPlain(await evaluator.evaluateRenderedConfig(configPath, content, workDir)) as Record<string, unknown>;
	const generate = generatedEntries(rendered.generate);
	for (const [name, entry] of generate) {
		const relativePath = entry.path;
		const contents = entry.contents;
		if (typeof relativePath !== 'string' || relativePath.length === 0) throw new Error(`generate "${name}" requires a non-empty path`);
		if (typeof contents !== 'string') throw new Error(`generate "${name}" requires string contents`);
		const root = await fs.realpath(workDir);
		const target = path.resolve(path.dirname(configPath), relativePath);
		// Both sides through realpath, or the comparison is between two
		// spellings of the same place. On macOS /var is a symlink to
		// /private/var, so a working directory under $TMPDIR resolved on one
		// side and not the other, and every generated file looked like an
		// escape from a directory it was sitting inside.
		//
		// The target may not exist yet -- it is what is about to be written --
		// so its DIRECTORY is resolved and the name appended.
		const targetDirectory = await fs.realpath(path.dirname(target));
		const resolvedTarget = path.join(targetDirectory, path.basename(target));
		const relative = path.relative(root, resolvedTarget);
		if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative)) throw new Error(`Generated file is outside the working directory: ${target}`);
		const exists = await pathExists(target);
		const ifExists = typeof entry.if_exists === 'string' ? entry.if_exists : 'overwrite_terragrunt';
		if (exists && (ifExists === 'skip' || ifExists === 'skip_if_exists')) continue;
		if (exists && ifExists === 'error') throw new Error(`Generated file already exists: ${target}`);
		// `overwrite_terragrunt` means "overwrite a file THIS TOOL generated",
		// not "overwrite whatever is there". Terragrunt enforces that with a
		// signature line and refuses a file without one, which is what stops a
		// generate block silently destroying something hand-written that
		// happens to share the name.
		if (exists && ifExists === 'overwrite_terragrunt') {
			const existing = await fs.readFile(target, 'utf8');
			if (!existing.startsWith(GENERATED_SIGNATURE)) {
				throw new Error(
					`Refusing to overwrite ${target}: it exists and was not generated by tghclparser`
				);
			}
		}
		await fs.mkdir(path.dirname(target), {recursive: true});
		await fs.writeFile(target, `${GENERATED_SIGNATURE}\n${contents}`, 'utf8');
	}
}

