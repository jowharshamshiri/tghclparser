/**
 * Exported so its behaviour can be tested by calling it.
 *
 * This is pure argument parsing -- no I/O, no subprocess -- and it was
 * covered by spawning nine `hcl validate` processes and reading their
 * stderr. That took 7.6 seconds against a 10-second timeout on an idle
 * machine, so the test failed whenever anything else was running. A flaky
 * test is worse than a missing one: it trains its readers to re-run rather
 * than to look.
 */
export function parseArgs(argv: string[]): CLIOptions | 'help' {
	const options: CLIOptions = { json: false, showConfigPath: false, experiments: [], workingDir: process.cwd(), paths: [], noHidden: false, dependencies: false, dag: false, offline: false };
	for (let index = 0; index < argv.length; index++) {
		const argument = argv[index];
		if (argument.startsWith('--format=')) {
			const value = argument.slice('--format='.length);
			if (!['text', 'json', 'tree', 'dot'].includes(value)) throw new Error(`Unsupported format ${value}`);
			options.format = value as CLIOptions['format'];
			continue;
		}
		if (argument.startsWith('--working-dir=')) {
			const value = argument.slice('--working-dir='.length);
			if (!value) throw new Error('--working-dir requires a path');
			options.workingDir = path.resolve(value);
			continue;
		}
		// Checked before the switch so the `--terragrunt-` spellings are covered
		// too; a switch can only match the literal names.
		if (isPassthroughFlag(argument)) continue;
		switch (argument) {
			case '--json': options.json = true; options.format = 'json'; break;
			case '--show-config-path': options.showConfigPath = true; break;
			case '--no-hidden': options.noHidden = true; break;
			case '--dependencies': options.dependencies = true; break;
			case '--dag': options.dag = true; break;
			case '--offline': options.offline = true; break;
			case '--format': {
				const value = argv[++index] as CLIOptions['format'];
				if (!value || !['text', 'json', 'tree', 'dot'].includes(value)) throw new Error(`Unsupported format ${value ?? ''}`);
				options.format = value;
				break;
			}
			case '--no-color':
			case '--no-tips':
			case '--non-interactive':
				break;
			case '--experiment': {
				const value = argv[++index];
				if (!value) throw new Error('--experiment requires a name');
				options.experiments.push(value);
				break;
			}
			case '--working-dir': {
				const value = argv[++index];
				if (!value) throw new Error('--working-dir requires a path');
				options.workingDir = path.resolve(value);
				break;
			}
			case '--help':
			case '-h': return 'help';
			default:
				if (argument.startsWith('-')) throw new Error(`Unknown option ${argument}`);
				options.paths.push(argument);
		}
	}
	return options;
}

interface DiscoveredConfig {
	type: 'unit' | 'stack';
	path: string;
	absPath: string;
}

export async function discoverConfigs(root: string, noHidden: boolean, displayRoot = root): Promise<DiscoveredConfig[]> {
	const result: DiscoveredConfig[] = [];
	const ignored = new Set(['.git', '.scrap', '.terraform', '.terragrunt-cache', '.terragrunt-stack', '.trash', 'node_modules']);
	const walk = async (directory: string): Promise<void> => {
		for (const entry of await fs.readdir(directory, {withFileTypes: true})) {
			if (entry.isDirectory()) {
				if (ignored.has(entry.name) || (noHidden && entry.name.startsWith('.'))) continue;
				await walk(path.join(directory, entry.name));
				continue;
			}
			if (!entry.isFile()) continue;
			if (entry.name !== 'terragrunt.hcl' && entry.name !== 'terragrunt.stack.hcl') continue;
			const absPath = path.join(directory, entry.name);
			result.push({type: entry.name === 'terragrunt.stack.hcl' ? 'stack' : 'unit', path: path.relative(displayRoot, directory) || '.', absPath});
		}
	};
	await walk(root);
	return result.sort((a, b) => a.path.localeCompare(b.path) || a.type.localeCompare(b.type));
}

function printFind(configs: DiscoveredConfig[], options: CLIOptions): void {
	const format = options.format ?? (options.json ? 'json' : 'text');
	if (format === 'json') {
		process.stdout.write(`${JSON.stringify(configs.map(({type, path: configPath}) => ({type, path: configPath})))}\n`);
		return;
	}
	if (format !== 'text') throw new Error(`Unsupported find format ${format}`);
	for (const config of configs) process.stdout.write(`${config.path}\n`);
}

function printList(configs: DiscoveredConfig[], options: CLIOptions): void {
	const format = options.format ?? 'text';
	if (format === 'text') {
		process.stdout.write(`${configs.map(config => config.path).join('  ')}  \n`);
		return;
	}
	if (format === 'tree') {
		for (const config of configs) process.stdout.write(`${config.path}\n`);
		return;
	}
	if (format !== 'dot') throw new Error(`Unsupported list format ${format}`);
	printDot(configs.map(config => ({path: config.path, dependencies: []})));
}

interface GraphComponent {
	path: string;
	dependencies: string[];
}

/** Writes components as Terragrunt's DOT renderer does: sorted by path, each followed by its edges. */
function printDot(components: GraphComponent[]): void {
	const byPath = (a: string, b: string): number => a < b ? -1 : a > b ? 1 : 0;
	process.stdout.write('digraph {\n');
	for (const component of [...components].sort((a, b) => byPath(a.path, b.path))) {
		process.stdout.write(`\t"${component.path}" ;\n`);
		for (const dependency of [...component.dependencies].sort(byPath)) process.stdout.write(`\t"${component.path}" -> "${dependency}";\n`);
	}
	process.stdout.write('}\n');
}

/**
 * Prints the discovered units and their dependencies the way Terragrunt's `dag graph` names them. Terragrunt names
 * a unit by the path it walked to it and a dependency by its config_path with symlinks resolved, each relative to
 * the working directory as given, so a dependency reached through a symlinked folder is the unit it resolves to.
 * Only the discovered units and stacks are listed: neither the files they include nor a dependency outside the
 * working directory is a node. Only a unit has dependency edges; a stack's components are not its dependencies.
 */
async function printDependencyGraph(workingDir: string, configs: DiscoveredConfig[]): Promise<void> {
	const workspace = new Workspace();
	workspace.setWorkspaceRoot(pathToFileURL(workingDir).toString());
	if (!await workspace.refreshDependencyTree()) throw new Error(`Unable to construct a configuration graph under ${workingDir}`);
	const components = await Promise.all(configs.map(async config => {
		if (config.type === 'stack') return {path: config.path, dependencies: []};
		const relationships = workspace.getRelationships(URI.file(config.absPath).toString());
		if (!relationships) throw new Error(`Discovered configuration ${config.absPath} is missing from the configuration graph`);
		const dependencies = await Promise.all(relationships.dependencies.map(async uri =>
			path.relative(workingDir, await fs.realpath(path.dirname(URI.parse(uri).fsPath)))
		));
		return {path: config.path, dependencies: [...new Set(dependencies)]};
	}));
	printDot(components);
}

