/**
 * The first line of every file a `generate` block writes.
 *
 * A marker, not a hash: it says the file is this tool's to overwrite, which is
 * what `if_exists = "overwrite_terragrunt"` actually asks about. Without it a
 * generate block would overwrite anything sharing the name, including a file
 * somebody wrote by hand.
 *
 * The signature is deliberately NOT terragrunt's. The two tools each refuse a
 * file bearing the other's mark, so a directory that has been generated into
 * by one is not silently taken over by the other -- and the message names
 * which tool wrote what.
 */
