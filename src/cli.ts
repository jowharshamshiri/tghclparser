/**
 * Flags that change presentation or prompting and carry no value.
 *
 * Each is accepted under its `--terragrunt-` spelling as well. Terragrunt
 * renamed these when it dropped the prefix, and a great many scripts still
 * pass the old names -- twenty-one occurrences of
 * `--terragrunt-non-interactive` in one deployment here. Refusing them makes
 * substituting this executable a rewrite of every caller, which is the
 * opposite of a drop-in replacement.
 *
 * Only flags this actually honours are aliased. A legacy flag accepted and
 * then ignored would be worse than one refused: the caller would believe it
 * had taken effect.
 */
const PASSTHROUGH_FLAGS = new Set(['--no-cas', '--no-color', '--no-tips', '--non-interactive']);

/** Whether an argument is one of those, under either spelling. */
function isPassthroughFlag(argument: string): boolean {
	if (PASSTHROUGH_FLAGS.has(argument)) return true;
	return argument.startsWith('--terragrunt-')
		&& PASSTHROUGH_FLAGS.has(`--${argument.slice('--terragrunt-'.length)}`);
}

