/** The flags a command was given on its command line, by name, and the arguments that are not flags. */
interface CommandFlags {
	values: Map<string, string[]>;
	switches: Map<string, boolean>;
	positional: string[];
}

/** The flags a command takes besides the global ones. */
interface CommandFlagTable {
	values: Record<string, 'once' | 'many'>;
	switches: string[];
	aliases?: Record<string, string>;
	/** The environment variables that set each of them, the current name first, as {@link GLOBAL_ENVIRONMENT}. */
	environment: Record<string, string[]>;
}

/** What a command was asked for, by its flags and by the environment variables that set them. */
export interface CommandSettings {
	/** Whether the flag was set at all, on the command line or in the environment, whatever its value. */
	given(flag: string): boolean;
	/** A switch's value: the command line's, else the environment's, else false. */
	switchOf(flag: string): boolean;
	/** A flag's values: the command line's, else the environment's; for an enabling flag, both. */
	valuesOf(flag: string): string[];
	/** The arguments that are not flags, those after `--` included. */
	positional: string[];
}

/**
 * Reads a command's flags as Terragrunt's command line does: the command's own and the global ones, with one dash or
 * two and a value after `=` or as the next argument; a flag that takes a value once, or a switch, refused when it is
 * given again; and each global flag's value checked as it is set.
 *
 * @param argv the arguments after the command's name; `--` ends the flags.
 * @param table the command's own flags.
 * @returns what was given.
 * @throws Error in Terragrunt's words when a flag is not one of the command's or the global ones, lacks its value,
 *   is given twice where it may be given once, or has a value it cannot take.
 */
function readCommandFlags(argv: string[], table: CommandFlagTable): CommandFlags {
	const valueFlags = { ...GLOBAL_VALUE_FLAGS, ...table.values };
	const switchNames = [...GLOBAL_SWITCHES, ...table.switches];
	const aliases = { ...GLOBAL_ALIASES, ...table.aliases };
	const flags: CommandFlags = { values: new Map(), switches: new Map(), positional: [] };
	let noColorSeen = false;
	for (let index = 0; index < argv.length; index++) {
		const argument = argv[index];
		// Terragrunt keeps only the first --no-color, in any spelling, before it reads the flags.
		if (argument.startsWith('-') && argument.slice(1).replace(/^-/, '').split('=')[0] === 'no-color') {
			if (noColorSeen) continue;
			noColorSeen = true;
		}
		if (argument === '--') {
			flags.positional.push(...argv.slice(index + 1));
			break;
		}
		if (!argument.startsWith('-') || argument === '-') {
			flags.positional.push(argument);
			continue;
		}
		if (argument.startsWith('---') || argument.startsWith('-=') || argument.startsWith('--=')) throw new Error(`bad flag syntax: ${argument}`);
		const body = argument.replace(/^--?/, '');
		const equals = body.indexOf('=');
		const written = equals < 0 ? body : body.slice(0, equals);
		const name = aliases[written] ?? written;
		const inline = equals < 0 ? undefined : body.slice(equals + 1);
		if (switchNames.includes(name)) {
			if (flags.switches.has(name)) {
				throw new Error(inline === undefined ? `invalid boolean flag ${written}: setting the flag multiple times` : `invalid boolean value "${inline}" for -${written}: setting the flag multiple times`);
			}
			const value = inline === undefined ? true : parseSwitch(inline);
			if (value === undefined) throw new Error(`invalid boolean value "${inline}" for -${written}: must be one of: "0", "1", "f", "t", "false", "true"`);
			flags.switches.set(name, value);
			continue;
		}
		const arity = valueFlags[name];
		if (arity === undefined) throw new Error(`flag provided but not defined: -${written}`);
		const value = inline ?? argv[++index];
		if (value === undefined) throw new Error(`flag needs an argument: -${written}`);
		const problem = globalValueProblem(name, value);
		if (problem !== undefined) throw new Error(`invalid value "${value}" for flag -${written}: ${problem}`);
		if (arity === 'once' && flags.values.has(name)) throw new Error(`invalid value "${value}" for flag -${written}: setting the flag multiple times`);
		flags.values.set(name, [...(flags.values.get(name) ?? []), value]);
	}
	return flags;
}

/**
 * Reads what a command was asked for as Terragrunt reads it: first the environment variable of each flag, the current
 * name before the deprecated ones, its value checked as the flag's would be, then the command line, which overrides
 * it. A deprecated variable that the command line does not override is warned about, or refused under strict mode
 * or a strict control against deprecated variables, and each completed experiment or strict control asked for is
 * warned about, since setting one no longer does anything. Neither warning is given when help or the version is
 * asked for.
 *
 * @param argv the arguments after the command's name.
 * @param table the command's own flags.
 * @param env the environment.
 * @returns what was asked for.
 * @throws Error in Terragrunt's words for a flag or variable that is refused or has a value it cannot take.
 */
function readCommandSettings(argv: string[], table: CommandFlagTable, env: NodeJS.ProcessEnv): CommandSettings {
	const environment = { ...GLOBAL_ENVIRONMENT, ...table.environment };
	const valueFlags = { ...GLOBAL_VALUE_FLAGS, ...table.values };
	const fromEnvironment = new Map<string, { name: string; value: string }>();
	const environmentSwitches = new Map<string, boolean>();
	const environmentValues = new Map<string, string[]>();
	const switchFromEnvironment = (name: string, text: string): boolean => {
		const value = parseSwitch(text);
		if (value === undefined) throw new Error(`invalid value "${text}" for env var ${name}: must be one of: "0", "1", "f", "t", "false", "true"`);
		return value;
	};
	for (const [flag, names] of Object.entries(environment)) {
		// An empty variable is unset.
		const name = names.find(candidate => env[candidate] !== undefined && env[candidate] !== '');
		if (name === undefined) continue;
		const text = env[name]!;
		fromEnvironment.set(flag, { name, value: text });
		if (valueFlags[flag] === undefined) {
			environmentSwitches.set(flag, switchFromEnvironment(name, text));
			continue;
		}
		const items = valueFlags[flag] === 'many' ? text.split(',') : [text];
		for (const item of items) {
			const problem = globalValueProblem(flag, item);
			if (problem !== undefined) throw new Error(`invalid value "${item}" for env var ${name}: ${problem}`);
		}
		environmentValues.set(flag, items);
	}
	// OpenTofu's TF_INPUT=false asks for what --non-interactive does, and is read when nothing else sets it.
	if (!environmentSwitches.has('non-interactive') && env.TF_INPUT !== undefined && env.TF_INPUT !== '') {
		environmentSwitches.set('non-interactive', !switchFromEnvironment('TF_INPUT', env.TF_INPUT));
	}
	const flags = readCommandFlags(argv, table);
	const settings: CommandSettings = {
		given: flag => flags.switches.has(flag) || flags.values.has(flag) || fromEnvironment.has(flag),
		switchOf: flag => flags.switches.get(flag) ?? environmentSwitches.get(flag) ?? false,
		valuesOf: flag => {
			const written = flags.values.get(flag);
			const set = environmentValues.get(flag) ?? [];
			if (ENABLING_FLAGS.includes(flag)) return [...set, ...written ?? []];
			return written ?? set;
		},
		positional: flags.positional
	};
	if (flags.switches.has('help') || flags.switches.has('version')) return settings;

	const controls = settings.valuesOf('strict-control');
	const strict = settings.switchOf('strict-mode') || controls.includes('deprecated-env-vars') || controls.includes('terragrunt-prefix-env-vars');
	for (const [flag, used] of fromEnvironment) {
		const current = environment[flag][0];
		if (used.name === current || flags.switches.has(flag) || flags.values.has(flag)) continue;
		if (strict || (LEGACY_LOG_ENVIRONMENT.includes(used.name) && controls.includes('legacy-logs'))) {
			throw new Error(`The \`${used.name}\` environment variable is no longer supported. Use \`${current}=${used.value}\` instead.`);
		}
		console.error(`The \`${used.name}\` environment variable is deprecated and will be removed in a future version of Terragrunt. Use \`${current}=${used.value}\` instead.`);
	}
	const experiments = [...new Set(settings.valuesOf('experiment'))].filter(name => EXPERIMENTS[name] === 'completed').sort();
	if (experiments.length > 0) {
		console.error(`The following experiment(s) are already completed: ${experiments.join(', ')}. Please remove any completed experiments, as setting them no longer does anything. For a list of all ongoing experiments, and the outcomes of previous experiments, see https://docs.terragrunt.com/reference/experiments`);
	}
	const completedControls = [...new Set(controls)].filter(name => STRICT_CONTROLS[name] === 'completed').sort();
	if (completedControls.length > 0) {
		console.error(`The following strict control(s) are already completed: ${completedControls.join(', ')}. Please remove any completed strict controls, as setting them no longer does anything. For a list of all ongoing strict controls, and the outcomes of previous strict controls, see https://docs.terragrunt.com/reference/strict-mode or get the actual list by running the \`terragrunt info strict\` command.`);
	}
	return settings;
}

/** The flags of `terragrunt hcl format` besides the global ones. */
const FORMAT_FLAGS: CommandFlagTable = {
	values: {
		'file': 'once', 'exclude-dir': 'many', 'filter': 'many', 'filters-file': 'once', 'discovery-boundary': 'once',
		'parallelism': 'once'
	},
	switches: [
		'check', 'diff', 'stdin', 'filter-affected', 'filter-allow-destroy', 'no-filters-file', 'queue-ignore-dag-order',
		'queue-ignore-errors'
	],
	environment: {
		'check': ['TG_CHECK', 'TG_HCLFMT_CHECK', 'TERRAGRUNT_CHECK'],
		'diff': ['TG_DIFF', 'TG_HCLFMT_DIFF', 'TERRAGRUNT_DIFF'],
		'stdin': ['TG_STDIN', 'TG_HCLFMT_STDIN', 'TERRAGRUNT_HCLFMT_STDIN'],
		'file': ['TG_FILE', 'TG_HCLFMT_FILE', 'TERRAGRUNT_HCLFMT_FILE'],
		'exclude-dir': ['TG_EXCLUDE_DIR', 'TG_HCLFMT_EXCLUDE_DIR', 'TERRAGRUNT_HCLFMT_EXCLUDE_DIR'],
		'filter': ['TG_FILTER'],
		'filter-affected': ['TG_FILTER_AFFECTED'],
		'filters-file': ['TG_FILTERS_FILE'],
		'no-filters-file': ['TG_NO_FILTERS_FILE']
	}
};

/** What `hcl format` was asked to do. */
interface FormatOptions {
	workingDir: string;
	/** Report what needs formatting and change nothing. */
	check: boolean;
	/** Print the difference formatting makes. */
	diff: boolean;
	/** Format standard input to standard output. */
	stdin: boolean;
	/** The one file to format, absolute; undefined to format the `.hcl` files under the working directory. */
	file: string | undefined;
	/** Names that are not walked into, beyond the ones never walked into. */
	excludeDirs: string[];
	/** The filters that select among the files found. */
	filters: Filter[];
}

/**
 * Reads a switch's value the way Go reads a boolean.
 *
 * @param value the text.
 * @returns the boolean, or undefined when the text is not one.
 */
function parseSwitch(value: string): boolean | undefined {
	if (['1', 't', 'T', 'TRUE', 'true', 'True'].includes(value)) return true;
	if (['0', 'f', 'F', 'FALSE', 'false', 'False'].includes(value)) return false;
	return undefined;
}

/**
 * Reads the lines of a filter file: one query to a line, without blank lines and `#` comments.
 *
 * @param file the file's absolute path.
 * @returns the lines, or none when the file does not exist.
 */
async function filterFileLines(file: string): Promise<string[]> {
	try {
		if (!(await fs.stat(file)).isFile()) return [];
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === 'ENOENT' || (error as NodeJS.ErrnoException).code === 'ENOTDIR') return [];
		throw error;
	}
	return (await fs.readFile(file, 'utf8')).replace(/\r\n/g, '\n').split('\n').map(line => line.trim()).filter(line => line !== '' && !line.startsWith('#'));
}

/**
 * Reads the arguments and environment of `hcl format`, which are those of `terragrunt hcl format`: the same flags,
 * with one dash or two, the same environment variables, and arguments that are not flags ignored.
 *
 * @param argv the arguments after `hcl format`.
 * @param env the environment.
 * @returns the options, or `help` or `version` when one of those was asked for.
 * @throws when a flag is not one of the command's, lacks its value, has a value it cannot take, or is given twice
 *   where it may be given once; and when a filter is not valid.
 */
async function parseFormatArgs(argv: string[], env: NodeJS.ProcessEnv): Promise<FormatOptions | 'help' | 'version'> {
	// An argument that is not a flag is ignored, as Terragrunt ignores it.
	const { given, switchOf, valuesOf } = readCommandSettings(argv, FORMAT_FLAGS, env);
	// Help and version are shown whatever value they are given, as Terragrunt shows them.
	if (given('help')) return 'help';
	if (given('version')) return 'version';
	const parallelism = valuesOf('parallelism')[0];
	if (parallelism !== undefined && !/^[+-]?\d+$/.test(parallelism)) throw new Error(`invalid value "${parallelism}" for flag -parallelism: must be 32-bit integer`);

	const workingDir = path.resolve(valuesOf('working-dir')[0] ?? process.cwd());
	// An empty value names no file, as when the flag is not given.
	const file = valuesOf('file')[0] || undefined;
	// The filters come from the flags, then from the two files Terragrunt reads in the working directory. The lines
	// of the excludes file are what to leave out, so each is negated.
	const queries = [...valuesOf('filter')];
	if (switchOf('filter-affected')) queries.push('[main...HEAD]');
	queries.push(...(await filterFileLines(path.resolve(workingDir, '.terragrunt-excludes'))).map(line => `!${line}`));
	if (!switchOf('no-filters-file')) queries.push(...await filterFileLines(path.resolve(workingDir, valuesOf('filters-file')[0] ?? '.terragrunt-filters')));
	const problems: string[] = [];
	const filters: Filter[] = [];
	for (const query of [...new Set(queries)]) {
		try {
			filters.push(parseFilter(query));
		} catch (error) {
			if (!(error instanceof FilterSyntaxError)) throw error;
			problems.push(error.message);
		}
	}
	if (problems.length > 0) throw new Error(problems.join('\n'));

	return {
		workingDir,
		check: switchOf('check'),
		diff: switchOf('diff'),
		stdin: switchOf('stdin'),
		file: file === undefined ? undefined : path.resolve(workingDir, file),
		excludeDirs: valuesOf('exclude-dir'),
		filters
	};
}

/**
 * Lists the files `hcl format` formats when none is named: every file under the working directory whose name ends
 * in `.hcl`, visited in the order of their names' bytes. Symbolic links to directories are not followed.
 *
 * Nothing with an excluded name is entered. As in Terragrunt, that holds for the working directory itself, and an
 * excluded name that is a file ends the visit of the directory it is in, so that what sorts after it there is left
 * out as well.
 *
 * @param root the working directory.
 * @param excluded the names not to enter.
 * @returns the absolute paths.
 */
async function collectFormatTargets(root: string, excluded: string[]): Promise<string[]> {
	const targets: string[] = [];
	/**
	 * Visits one path.
	 *
	 * @param target the path.
	 * @param isDirectory whether it is a directory.
	 * @returns false when the visit of the directory holding it ends here.
	 */
	const visit = async (target: string, isDirectory: boolean): Promise<boolean> => {
		if (excluded.includes(path.basename(target))) return isDirectory;
		if (!isDirectory) {
			if (target.endsWith('.hcl')) targets.push(target);
			return true;
		}
		const entries = await fs.readdir(target, {withFileTypes: true});
		entries.sort((left, right) => Buffer.compare(Buffer.from(left.name), Buffer.from(right.name)));
		for (const entry of entries) {
			if (!(await visit(path.join(target, entry.name), entry.isDirectory()))) break;
		}
		return true;
	};
	await visit(root, (await fs.lstat(root)).isDirectory());
	return targets;
}

/**
 * Formats one source for `hcl format` and reports the difference when asked.
 *
 * @param original the source text.
 * @param name how the diff names the source.
 * @param options what was asked for.
 * @returns the formatted text and whether it differs from the original.
 * @throws {HclSyntaxError} when the source is not valid HCL.
 */
function formatSource(original: string, name: string, options: FormatOptions): {formatted: string; changed: boolean} {
	const formatted = formatHcl(original, name);
	const changed = formatted !== original;
	if (changed && options.diff) {
		// Diff labels use forward slashes on every platform, as Terragrunt's do.
		const label = name.split(path.sep).join('/');
		process.stdout.write(unifiedDiff(path.posix.join('old', label), original, path.posix.join('new', label), formatted));
	}
	return {formatted, changed};
}

/**
 * Prints the version of this tool, which is the version of the package this file is in.
 *
 * The package's manifest sits one directory above this file, in a checkout and in an installed copy alike. The
 * program is found through the path it was started by with links resolved, because an installed copy is started
 * through the link npm makes in a `bin` directory, and the manifest is not beside that.
 *
 * @throws when the manifest cannot be read or holds no version.
 */
async function printVersion(): Promise<void> {
	const entry = process.argv[1];
	if (!entry) throw new Error('Unable to determine tghclp version: the program was started without a path');
	const manifestFile = path.resolve(path.dirname(await fs.realpath(entry)), '../package.json');
	let version: unknown;
	try {
		version = (JSON.parse(await fs.readFile(manifestFile, 'utf8')) as {version?: unknown}).version;
	} catch (error) {
		throw new Error(`Unable to determine tghclp version: cannot read ${manifestFile}: ${error instanceof Error ? error.message : String(error)}`);
	}
	if (typeof version !== 'string' || version === '') throw new Error(`Unable to determine tghclp version: ${manifestFile} holds no version`);
	process.stdout.write(`${version}\n`);
}

/**
 * Runs `hcl format`, which does what `terragrunt hcl format` does: rewrites every `.hcl` file under the working
 * directory that the filters select, or the one file named, or standard input, into the canonical layout. A file
 * that is not valid HCL is reported and left alone, and the rest are still formatted.
 *
 * `--diff` prints what changes and, as in Terragrunt, still changes the files unless `--check` is given too.
 * `--check` changes nothing and fails when anything needs formatting.
 *
 * @param argv the arguments after `hcl format`.
 * @returns 0 when everything was formatted, or was already; 1 when a file could not be parsed or read, or
 *   `--check` found one that needs formatting.
 */
async function formatHCL(argv: string[]): Promise<number> {
	const options = await parseFormatArgs(argv, process.env);
	if (options === 'version') {
		await printVersion();
		return 0;
	}
	if (options === 'help') {
		console.log([
			'Usage: tghclp hcl format [options]',
			'',
			'Recursively find HCL files and rewrite them into the canonical format, as terragrunt hcl format does.',
			'The flags and environment variables are those of terragrunt hcl format.',
			'',
			'Options:',
			'  --working-dir <path>    Directory to search (default: current directory)  [$TG_WORKING_DIR]',
			'  --file <path>           The one file to format, relative to the working directory  [$TG_FILE]',
			'  --exclude-dir <name>    A directory name to skip; may be repeated  [$TG_EXCLUDE_DIR]',
			'  --filter <query>        A path filter selecting the files to format; may be repeated  [$TG_FILTER]',
			'  --filters-file <path>   A file of filter queries, one per line (default: .terragrunt-filters)',
			'  --no-filters-file       Do not read the filters file',
			'  --check                 Change nothing; exit 1 when a file needs formatting  [$TG_CHECK]',
			'  --diff                  Print the difference between each file and its formatted version  [$TG_DIFF]',
			'  --stdin                 Format standard input and print the result  [$TG_STDIN]',
			'  --help                  Show this help'
		].join('\n'));
		return 0;
	}
	const decoder = new TextDecoder('utf-8', {fatal: true, ignoreBOM: true});
	/**
	 * Decodes source bytes, refusing ones that are not UTF-8 rather than rewriting them.
	 *
	 * @param bytes the bytes read.
	 * @param name how the message names the source.
	 * @returns the text.
	 */
	const decode = (bytes: Uint8Array, name: string) => {
		try {
			return decoder.decode(bytes);
		} catch {
			throw new Error(`${name} is not valid UTF-8; all input files must be UTF-8 encoded`);
		}
	};
	if (options.stdin) {
		if (options.file !== undefined) throw new Error('both stdin and path flags are specified');
		try {
			const {formatted, changed} = formatSource(decode(fsSync.readFileSync(0), 'stdin'), 'stdin', options);
			if (options.check && changed) {
				console.error("File 'stdin' needs formatting");
				return 1;
			}
			if (!options.check && !options.diff) process.stdout.write(formatted);
			return 0;
		} catch (error) {
			if (!(error instanceof Error)) throw error;
			console.error(`error parsing hcl from stdin: ${error.message}`);
			return 1;
		}
	}
	const targets = options.file !== undefined
		? [options.file]
		: filterFiles(options.filters, await collectFormatTargets(options.workingDir, [...FORMAT_EXCLUDED_NAMES, ...options.excludeDirs]), options.workingDir, path.sep);
	let failed = false;
	for (const target of targets) {
		try {
			const original = decode(await fs.readFile(target), target);
			const {formatted, changed} = formatSource(original, target, options);
			if (!changed) continue;
			if (options.check) {
				failed = true;
				console.error(`File '${target}' needs formatting`);
				continue;
			}
			// Writing into the existing file keeps its permissions.
			await fs.writeFile(target, formatted);
		} catch (error) {
			if (!(error instanceof Error)) throw error;
			failed = true;
			console.error(error instanceof HclSyntaxError ? `Error parsing ${target}: ${error.message}` : `Error formatting ${target}: ${error.message}`);
		}
	}
	return failed ? 1 : 0;
}

function offsetPosition(content: string, offset: number): {line: number; character: number} {
	const lines = content.slice(0, offset).split('\n');
	return {line: lines.length - 1, character: lines[lines.length - 1].length};
}

/**
 * A rendered configuration as Terragrunt's `render --json` writes it: Terragrunt reads go-cty's JSON back with Go's
 * encoding/json, which takes each number as the float64 nearest its decimal text, and writes that float64 in full
 * digits, or with an exponent when it is below 1e-6 or from 1e21, and each object's keys in the order of their bytes.
 *
 * @param plain the configuration, as {@link runtimeValueToPlain} gives it.
 * @returns the JSON text.
 * @throws Error in Go's words for a number beyond the largest float64.
 */
function renderedJson(plain: unknown): string {
	const write = (value: unknown, path: string): string => {
		if (value instanceof CtyNumber) {
			const text = value.toString();
			const float = Number(text);
			if (!Number.isFinite(float)) {
				throw new Error(`json: cannot unmarshal number ${text} into Go struct field CtyJSONOutput.value${path} of type float64`);
			}
			return goJsonFloat(float);
		}
		if (Array.isArray(value)) return `[${value.map((item, index) => write(item, `${path}.${index}`)).join(',')}]`;
		if (isRecord(value)) {
			return `{${Object.keys(value).sort(compareStrings).map(key => `${goJsonString(key)}:${write(value[key], `${path}.${key}`)}`).join(',')}}`;
		}
		return typeof value === 'string' ? goJsonString(value) : JSON.stringify(value);
	};
	return write(plain, '');
}

/** A string as Go's encoding/json writes it: as JSON does, and with `<`, `>`, `&`, U+2028 and U+2029 escaped too. */
function goJsonString(value: string): string {
	return JSON.stringify(value).replace(/[<>&\u2028\u2029]/g, character => `\\u${character.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

/**
 * A float64 as Go's encoding/json writes it: the fewest digits that read back to it, as strconv gives them and as
 * JavaScript's toExponential gives them too, with an exponent below 1e-6 or from 1e21, written `e-7` or `e+21`.
 */
function goJsonFloat(value: number): string {
	const sign = value < 0 || Object.is(value, -0) ? '-' : '';
	const magnitude = Math.abs(value);
	if (magnitude === 0) return `${sign}0`;
	const [mantissa, exponentText] = magnitude.toExponential().split('e');
	const digits = mantissa.replace('.', '');
	const exponent = Number(exponentText);
	if (magnitude < 1e-6 || magnitude >= 1e21) {
		const fraction = digits.length > 1 ? `.${digits.slice(1)}` : '';
		return `${sign}${digits[0]}${fraction}e${exponent < 0 ? '-' : '+'}${Math.abs(exponent)}`;
	}
	const point = exponent + 1;
	if (point <= 0) return `${sign}0.${'0'.repeat(-point)}${digits}`;
	if (point >= digits.length) return `${sign}${digits}${'0'.repeat(point - digits.length)}`;
	return `${sign}${digits.slice(0, point)}.${digits.slice(point)}`;
}

function hclValue(value: unknown): string {
	if (typeof value === 'string') return JSON.stringify(value);
	if (typeof value === 'boolean' || value instanceof CtyNumber) return String(value);
	if (value === null) return 'null';
	if (Array.isArray(value)) return `[${value.map(hclValue).join(', ')}]`;
	if (typeof value === 'object') return `{ ${Object.entries(value as Record<string, unknown>).map(([key, item]) => `${key} = ${hclValue(item)}`).join(', ')} }`;
	throw new Error(`Cannot serialize stack value of type ${typeof value}`);
}

async function copyDirectory(source: string, target: string): Promise<void> {
	await fs.mkdir(target, {recursive: true});
	for (const entry of await fs.readdir(source, {withFileTypes: true})) {
		const from = path.join(source, entry.name);
		const to = path.join(target, entry.name);
		if (entry.isDirectory()) await copyDirectory(from, to);
		else if (entry.isFile()) await fs.copyFile(from, to);
		else throw new Error(`Unsupported stack source entry: ${from}`);
	}
}

export async function stackGenerate(argv: string[]): Promise<number> {
	let workingDir = process.cwd();
	for (let index = 0; index < argv.length; index++) {
		const argument = argv[index];
		if (argument === '--help' || argument === '-h') {
			console.log('Usage: tghclp stack generate [--working-dir <path>]');
			return 0;
		}
		if (argument === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
			continue;
		}
		if (argument.startsWith('--working-dir=')) {
			workingDir = path.resolve(argument.slice('--working-dir='.length));
			continue;
		}
		if (isPassthroughFlag(argument)) continue;
		if (argument.startsWith('-')) throw new Error(`Unknown stack generate option ${argument}`);
	}
	const stackPath = path.join(workingDir, 'terragrunt.stack.hcl');
	const content = await fs.readFile(stackPath, 'utf8');
	const document = new ParsedDocument(new Workspace(), pathToFileURL(stackPath).toString(), content);
	const ast: any = document.getAST();
	if (!ast || document.getDiagnostics().length > 0) throw new Error(`Invalid stack configuration: ${stackPath}`);
	const evaluator = evaluatorFor();
	const blocks: any[] = [];
	const visit = (node: any): void => {
		if (node.type === 'block' && (node.value === 'unit' || node.value === 'stack')) blocks.push(node);
		for (const child of node.children ?? []) visit(child);
	};
	visit(ast);
	if (blocks.length === 0) {
		console.warn(`No stack files found in ${workingDir} Nothing to generate.`);
		return 0;
	}
	for (const block of blocks) {
		const attribute = (name: string): any => block.children?.find((child: any) => child.type === 'attribute' && child.value === name);
		const evaluate = async (name: string): Promise<unknown> => {
			const item = attribute(name);
			if (!item) return undefined;
			const value = item.children?.find((child: any) => child.type !== 'attribute_identifier');
			if (!value?.location?.start || value.location.start.offset === undefined) throw new Error(`${name} in ${block.value} is missing a value`);
			const result = await evaluator.evaluateAtPosition(stackPath, content, workingDir, offsetPosition(content, value.location.start.offset));
			if (!result) throw new Error(`Unable to evaluate ${name} in ${stackPath}`);
			return runtimeValueToPlain(result);
		};
		const source = await evaluate('source');
		const generatedPath = await evaluate('path');
		if (typeof source !== 'string' || typeof generatedPath !== 'string' || source === '' || generatedPath === '') throw new Error(`${block.value} requires non-empty source and path attributes`);
		const root = await fs.realpath(workingDir);
		const acquired = await acquireModuleSource(source, root);
		const sourceRelative = path.relative(root, acquired.root);
		if (isLocalSource(splitModuleSource(source).repository) && (sourceRelative === '..' || sourceRelative.startsWith(`..${path.sep}`) || path.isAbsolute(sourceRelative))) {
			await acquired.cleanup();
			throw new Error(`Stack source must be inside the working directory: ${source}`);
		}
		const noDot = Boolean(await evaluate('no_dot_terragrunt_stack'));
		const targetDir = path.resolve(root, noDot ? generatedPath : path.join('.terragrunt-stack', generatedPath));
		try {
			const realSource = acquired.root;
			const relativeTarget = path.relative(root, targetDir);
			if (relativeTarget === '..' || relativeTarget.startsWith(`..${path.sep}`) || path.isAbsolute(relativeTarget)) throw new Error(`Generated stack target is outside the working directory: ${targetDir}`);
			if (realSource === targetDir) throw new Error(`Generated stack source and target are identical: ${targetDir}`);
			await fs.access(realSource);
			await fs.rm(targetDir, {recursive: true, force: true});
			await copyDirectory(realSource, targetDir);
			const values = await evaluate('values');
			if (values !== undefined) {
				if (!isRecord(values)) throw new Error(`${block.value} values must evaluate to an object`);
				const entries = Object.entries(values as Record<string, unknown>).sort(([left], [right]) => left.localeCompare(right));
				const width = Math.max(...entries.map(([key]) => key.length));
				const valuesText = '# Auto-generated by the terragrunt.stack.hcl file by Terragrunt. Do not edit manually\n' + entries.map(([key, value]) => `${key.padEnd(width)} = ${hclValue(value)}`).join('\n') + '\n';
				await fs.writeFile(path.join(targetDir, 'terragrunt.values.hcl'), valuesText);
			}
		} finally {
			await acquired.cleanup();
		}
		console.log(`Generated ${block.value} ${String(block.children?.find((child: any) => child.type === 'parameter')?.value ?? '')}`.trim());
	}
	return 0;
}

async function stackLifecycle(command: 'run' | 'output' | 'clean', argv: string[]): Promise<number> {
	let workingDir = process.cwd();
	for (let index = 0; index < argv.length; index++) {
		if (argv[index] === '--working-dir') {
			const value = argv[++index];
			if (!value) throw new Error('--working-dir requires a path');
			workingDir = path.resolve(value);
		} else if (argv[index]?.startsWith('--working-dir=')) {
			workingDir = path.resolve(argv[index].slice('--working-dir='.length));
		} else if (argv[index] === '--help' || argv[index] === '-h') {
			console.log(`Usage: tghclp stack ${command} [--working-dir <path>]${command === 'run' || command === 'output' ? ' <command> [arguments...]' : ''}`);
			return 0;
		}
	}
	const root = await fs.realpath(workingDir);
	const generated = path.join(root, '.terragrunt-stack');
	if (command === 'clean') {
		await fs.rm(generated, {recursive: true, force: true});
		return 0;
	}
	await stackGenerate(argv.filter((argument, index) => argument === '--working-dir' || argument.startsWith('--working-dir=') || (argv[index - 1] === '--working-dir')));
	const generatedRoot = await fs.realpath(generated);
	const executionArgs = ['--all', '--working-dir', generatedRoot];
	for (let index = 0; index < argv.length; index++) {
		if (argv[index] === '--working-dir') { index++; continue; }
		if (argv[index]?.startsWith('--working-dir=')) continue;
		if (isPassthroughFlag(argv[index])) { executionArgs.push(argv[index]); continue; }
		executionArgs.push(argv[index]);
	}
	if (executionArgs.length === 3) throw new Error(`stack ${command} requires a command`);
	return executeTerraformCommand(executionArgs);
}

