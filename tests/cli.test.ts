	it('signs generated files and refuses to overwrite ones it did not write', async () => {
		// `if_exists = "overwrite_terragrunt"` asks to overwrite a file THIS
		// tool generated, not whatever happens to share the name. The signature
		// line is how that is known, and without it a generate block would
		// destroy a hand-written file silently.
		//
		// The signature is deliberately not terragrunt's: each tool refuses a
		// file bearing the other's mark, so a directory generated into by one
		// is not quietly taken over by the other. Verified against terragrunt
		// 0.67.1, which refuses a tghclparser-signed file in exactly this way.
		const cli = path.resolve('dist/cli.cjs');
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclparser-sig-'));
		await fs.mkdir(path.join(root, '.git'));
		await fs.writeFile(path.join(root, 'terragrunt.hcl'), [
			'generate "g" {',
			'  path      = "out.tf"',
			'  if_exists = "overwrite_terragrunt"',
			'  contents  = "locals { a = 1 }"',
			'}'
		].join('\n'));
		const unit = path.join(root, 'unit');
		await fs.mkdir(unit);
		await fs.writeFile(
			path.join(unit, 'terragrunt.hcl'),
			'include "root" {\n  path = find_in_parent_folders("terragrunt.hcl")\n}\n'
		);
		const target = path.join(unit, 'out.tf');
		const args = [cli, 'init', '--working-dir', unit, '--tf-path', '/bin/echo'];

		// Generation happens before tofu runs, so what matters is the file
		// written, not the stub binary's exit status.
		spawnSync(process.execPath, args, {cwd: unit, encoding: 'utf8'});
		const written = await fs.readFile(target, 'utf8');
		expect(written.split('\n')[0]).to.match(/^# Generated by tghclparser\. Sig: /u);
		expect(written).to.contain('locals { a = 1 }');

		// Its own file is overwritten, which is what the setting asks for.
		const second = spawnSync(process.execPath, args, {cwd: unit, encoding: 'utf8'});
		expect(`${second.stdout}${second.stderr}`).to.not.contain('not generated by tghclparser');

		// A file it did not write is left exactly as it was found.
		await fs.writeFile(target, '# written by hand\n');
		const refused = spawnSync(process.execPath, args, {cwd: unit, encoding: 'utf8'});
		expect(`${refused.stdout}${refused.stderr}`).to.contain('not generated by tghclparser');
		expect(await fs.readFile(target, 'utf8')).to.equal('# written by hand\n');

		// Including one terragrunt itself generated.
		await fs.writeFile(target, '# Generated by Terragrunt. Sig: nIlQXj57tbuaRZEa\nlocals {}\n');
		const foreign = spawnSync(process.execPath, args, {cwd: unit, encoding: 'utf8'});
		expect(`${foreign.stdout}${foreign.stderr}`).to.contain('not generated by tghclparser');
		expect(await fs.readFile(target, 'utf8')).to.contain('Generated by Terragrunt');

		await fs.rm(root, {recursive: true, force: true});
	});

