import {expect} from 'chai';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import {discoverConfigs} from '../src/cli';
import {stackGenerate} from '../src/cli';
import {spawnSync} from 'node:child_process';

describe('CLI configuration discovery', () => {
	it('discovers units and stacks in stable relative order', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-cli-'));
		await fs.mkdir(path.join(root, 'z', '.hidden'), {recursive: true});
		await fs.mkdir(path.join(root, 'a'), {recursive: true});
		await fs.writeFile(path.join(root, 'z', 'terragrunt.stack.hcl'), 'unit "app" { source = "." path = "app" }');
		await fs.writeFile(path.join(root, 'a', 'terragrunt.hcl'), 'inputs = {}');
		await fs.writeFile(path.join(root, 'z', '.hidden', 'terragrunt.hcl'), 'inputs = {}');

		const visible = await discoverConfigs(root, true);
		expect(visible.map(config => [config.type, config.path])).to.deep.equal([
			['unit', 'a'],
			['stack', 'z']
		]);

		const all = await discoverConfigs(root, false);
		expect(all.map(config => config.path)).to.deep.equal(['a', 'z', 'z/.hidden']);
		await fs.rm(root, {recursive: true, force: true});
	});

	it('generates a local stack component and evaluated values file', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-stack-'));
		await fs.mkdir(path.join(root, 'modules', 'app'), {recursive: true});
		await fs.writeFile(path.join(root, 'modules', 'app', 'terragrunt.hcl'), 'inputs = { from = "source" }\n');
		await fs.writeFile(path.join(root, 'terragrunt.stack.hcl'), [
			'unit "app" {',
			'  source = "./modules/app"',
			'  path = "generated/app"',
			'  values = { region = "eu" replicas = 2 }',
			'}',
			''
		].join('\n'));
		const result = await stackGenerate(['--working-dir', root]);
		expect(result).to.equal(0);
		expect(await fs.readFile(path.join(root, '.terragrunt-stack', 'generated', 'app', 'terragrunt.hcl'), 'utf8')).to.equal('inputs = { from = "source" }\n');
		expect(await fs.readFile(path.join(root, '.terragrunt-stack', 'generated', 'app', 'terragrunt.values.hcl'), 'utf8')).to.equal('# Auto-generated by the terragrunt.stack.hcl file by Terragrunt. Do not edit manually\nregion   = "eu"\nreplicas = 2\n');
		await fs.rm(root, {recursive: true, force: true});
	});

	it('scaffolds a local module without unresolved placeholders', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-scaffold-'));
		const moduleDir = path.join(root, 'module');
		const outputDir = path.join(root, 'generated');
		await fs.mkdir(moduleDir, {recursive: true});
		await fs.writeFile(path.join(moduleDir, 'variables.tf'), [
			'variable "region" {',
			'  description = "Deployment region"',
			'  default = "eu-west-1"',
			'}',
			'variable "name" {',
			'  description = "Service name"',
			'}',
			''
		].join('\n'));
		const cli = path.resolve('dist/cli.cjs');
		const result = spawnSync(process.execPath, [cli, 'scaffold', './module', '--working-dir', root, '--output-folder', 'generated', '--var', 'name=api', '--no-include-root'], {encoding: 'utf8'});
		expect(result.status).to.equal(0, result.stderr);
		expect(await fs.readFile(path.join(outputDir, 'terragrunt.hcl'), 'utf8')).to.equal([
			'terraform {',
			'  source = "./module"',
			'}',
			'',
			'inputs = {',
			'  name = "api"',
			'  region = "eu-west-1"',
			'}',
			''
		].join('\n'));
		await fs.rm(root, {recursive: true, force: true});
	});

	it('lists local catalog components as JSON lines only with the catalog experiment', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-catalog-'));
		const catalog = path.join(root, 'catalog');
		const component = path.join(catalog, 'network');
		await fs.mkdir(component, {recursive: true});
		await fs.writeFile(path.join(root, 'terragrunt.hcl'), 'catalog { urls = ["./catalog"] }\n');
		await fs.writeFile(path.join(component, 'terragrunt.hcl'), 'terraform { source = "./module" }\n');
		const cli = path.resolve('dist/cli.cjs');
		const rejected = spawnSync(process.execPath, [cli, 'catalog', '--format=jsonl', '--working-dir', root], {encoding: 'utf8'});
		expect(rejected.status).to.not.equal(0);
		const result = spawnSync(process.execPath, [cli, 'catalog', '--format=jsonl', '--experiment=catalog-format', '--working-dir', root], {encoding: 'utf8'});
		expect(result.status).to.equal(0, result.stderr);
		expect(JSON.parse(result.stdout)).to.deep.equal({kind: 'unit', title: 'network', description: '', source: './catalog', dir: 'network', component_source: './module', copyable: true});
		await fs.rm(root, {recursive: true, force: true});
	});

	it('runs all units in dependency order', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-run-all-'));
		await fs.mkdir(path.join(root, 'app'), {recursive: true});
		await fs.mkdir(path.join(root, 'database'), {recursive: true});
		await fs.writeFile(path.join(root, 'app', 'terragrunt.hcl'), 'dependency "database" { config_path = "../database" }\ninputs = {}\n');
		await fs.writeFile(path.join(root, 'database', 'terragrunt.hcl'), 'inputs = {}\n');
		const cli = path.resolve('dist/cli.cjs');
		const result = spawnSync(process.execPath, [cli, 'run', '--all', '--tf-path', '/bin/echo', '--working-dir', root, 'plan'], {encoding: 'utf8'});
		expect(result.status).to.equal(0, result.stderr);
		expect(result.stdout).to.equal('plan\nplan\n');
		await fs.rm(root, {recursive: true, force: true});
	});

	it('performs local backend bootstrap and forced state deletion', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-backend-'));
		await fs.writeFile(path.join(root, 'terragrunt.hcl'), 'remote_state { backend = "local" config = { path = "state.tfstate" } }\n');
		await fs.writeFile(path.join(root, 'state.tfstate'), '{}\n');
		const cli = path.resolve('dist/cli.cjs');
		const bootstrap = spawnSync(process.execPath, [cli, 'backend', 'bootstrap', '--tf-path', '/bin/echo', '--working-dir', root], {encoding: 'utf8'});
		expect(bootstrap.status).to.equal(0, bootstrap.stderr);
		expect(bootstrap.stderr).to.contain('Bootstrap for local backend not implemented.');
		const deleted = spawnSync(process.execPath, [cli, 'backend', 'delete', '--force', '--working-dir', root], {encoding: 'utf8'});
		expect(deleted.status).to.equal(0, deleted.stderr);
		let stateExists = true;
		try { await fs.access(path.join(root, 'state.tfstate')); } catch { stateExists = false; }
		expect(stateExists).to.equal(true);
		await fs.rm(root, {recursive: true, force: true});
	});

	it('runs lifecycle hooks around the selected IaC command', async () => {
		const root = await fs.mkdtemp(path.join(os.tmpdir(), 'tghclp-hooks-'));
		await fs.writeFile(path.join(root, 'terragrunt.hcl'), [
			'terraform {',
			'  before_hook "before" { commands = ["plan"] execute = ["/bin/echo", "before"] }',
			'  after_hook "after" { commands = ["plan"] execute = ["/bin/echo", "after"] }',
			'}',
			'inputs = {}',
			''
		].join('\n'));
		const cli = path.resolve('dist/cli.cjs');
		const result = spawnSync(process.execPath, [cli, 'run', '--tf-path', '/bin/echo', '--working-dir', root, 'plan'], {encoding: 'utf8'});
		expect(result.status).to.equal(0, result.stderr);
		expect(result.stdout).to.equal('before\nplan\nafter\n');
		await fs.rm(root, {recursive: true, force: true});
	});
});
